#!/usr/bin/env python3
"""Render open-mics/open-mics.json into open-mics/index.html (between the mics:start/end markers).

  python3 _tools/open_mics.py           rewrite the page from the JSON
  python3 _tools/open_mics.py --check   exit 1 if the page is out of date or the JSON is invalid

Entries whose `confirmed` date is older than hide_after_days are left out at build time; the page's
inline script also hides them (and past `next` dates) at view time, so a stale build still ages out.
"""
import datetime as dt, html, json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA, PAGE = ROOT / "open-mics/open-mics.json", ROOT / "open-mics/index.html"
START, END = "<!-- mics:start (generated by _tools/open_mics.py, edit open-mics.json) -->", "<!-- mics:end -->"
REQUIRED = ("id", "venue", "area", "address", "day", "when", "details", "source", "confirmed")
DAYS = "Sun Mon Tue Wed Thu Fri Sat".split()

def load():
    d = json.loads(DATA.read_text())
    ids = set()
    for m in d["mics"]:
        miss = [k for k in REQUIRED if not m.get(k) and m.get(k) != 0]
        if miss: sys.exit(f"{m.get('id', '?')}: missing {miss}")
        if m["id"] in ids: sys.exit(f"duplicate id {m['id']}")
        ids.add(m["id"])
        if m["id"] in d.get("opted_out", []): sys.exit(f"{m['id']}: host opted out, remove it")
        if not m["source"].startswith("https://"): sys.exit(f"{m['id']}: source must be https")
        for k in ("confirmed", "next"):
            if k in m: dt.date.fromisoformat(m[k])
        if m["day"] not in range(7): sys.exit(f"{m['id']}: day must be 0 (Sun) to 6 (Sat)")
    return d

def fmt(d):  # "Nov 14, 2026"
    return f"{d:%b} {d.day}, {d.year}"

def render(d, today):
    keep = [m for m in d["mics"] if (today - dt.date.fromisoformat(m["confirmed"])).days <= d["hide_after_days"]]
    keep.sort(key=lambda m: ((m["day"] - 1) % 7, m["when"]))  # Monday first
    e = lambda s: html.escape(s, quote=True)
    out = []
    for m in keep:
        conf = dt.date.fromisoformat(m["confirmed"])
        nxt = ""
        if m.get("next") and dt.date.fromisoformat(m["next"]) >= today:
            n = dt.date.fromisoformat(m["next"])
            nxt = f'<p class="mic-next" data-next="{n}">Next one: {DAYS[(n.weekday() + 1) % 7]}, {fmt(n)}</p>'
        maps = "https://maps.google.com/?q=" + re.sub(r"\s+", "+", m["address"])
        out.append(
            f'<li class="mic" id="{e(m["id"])}" data-confirmed="{conf}">'
            f'<p class="mic-when">{e(m["when"])}</p>'
            f'<h3>{e(m["venue"])}</h3>'
            f'<p class="mic-where">{e(m["area"])} · <a href="{e(maps)}">{e(m["address"])}</a></p>'
            f'<p>{e(m["details"])}</p>{nxt}'
            f'<p class="mic-check">Checked {fmt(conf)} · <a href="{e(m["source"])}">Source ↗</a></p></li>')
    return "\n".join(['<ul class="mics" data-hide-after="%d">' % d["hide_after_days"], *out, "</ul>"])

def main():
    d, today = load(), dt.date.today()
    page = PAGE.read_text()
    i, j = page.index(START) + len(START), page.index(END)
    new = page[:i] + "\n" + render(d, today) + "\n" + page[j:]
    if "--check" in sys.argv:
        if new != page: sys.exit("open-mics/index.html is out of date: run python3 _tools/open_mics.py")
        print("ok"); return
    PAGE.write_text(new)
    shown = new.count('class="mic"')
    print(f"rendered {shown} of {len(d['mics'])} mics")

if __name__ == "__main__":
    main()
